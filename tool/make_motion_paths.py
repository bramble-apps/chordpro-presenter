#!/usr/bin/env python3
"""Writes lib/widgets/motion_paths.dart: the outlines of the toolbar icons that move on hover
(lib/widgets/motion_icon.dart), taken from assets/icons/BrambleIcons.ttf and split into their
separate shapes (each with its holes), on the icons' 24 × 24 grid, y down. The moving icons draw
these shapes one by one, so each part (an arrow, a square, a line) can move on its own.

    make_motion_paths.py            (run after tool/make_bramble_icons.py)

Needs fonttools."""
import os, re
from fontTools.ttLib import TTFont
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ICONS = [  # Dart name -> glyph (set:name), as in tool/bramble_icons.txt
    ('share', 'ph:export'), ('annotate', 'ph:pen-nib'), ('structure', 'tb:list-tree'),
    ('format', 'ph:paint-brush'), ('present', 'ph:squares-four'), ('projector', 'ph:projector-screen'),
    ('preview', 'tb:picture-in-picture'), ('sticky', 'tb:note'), ('insert', 'tb:photo-plus'),
    ('more', 'ph:dots-three-circle'), ('autoscroll', 'ph:caret-double-down'), ('tuner', 'ph:waveform'),
    ('pads', 'ph:waves'), ('note', 'ph:music-note'), ('play', 'tb:player-play'),
    ('blackout', 'ph:eye-slash'),
]
UPM, ASC = 1024, 896
S = 24 / UPM


def main():
    font = TTFont(os.path.join(ROOT, 'assets/icons/BrambleIcons.ttf'))
    cmap, gs = font.getBestCmap(), font.getGlyphSet()
    src = open(os.path.join(ROOT, 'lib/bramble_icons.dart')).read()
    cps = {m.group(1): int(m.group(2), 16) for m in re.finditer(
        r'/// (\S+)\n\s+static const IconData \w+ =\s*IconData\(\s*0x([0-9A-F]+)', src)}
    out = [
        '// Generated by tool/make_motion_paths.py from assets/icons/BrambleIcons.ttf: do not edit.',
        '//',
        '// The moving toolbar icons\' shapes (SVG path data on the 24 × 24 grid, y down), each',
        '// shape with its holes, in the order the font has them.',
        '',
        'const Map<String, List<String>> motionPaths = {',
    ]
    for name, glyph in ICONS:
        rec = DecomposingRecordingPen(gs)
        gs[cmap[cps[glyph]]].draw(rec)
        contours, cur = [], []
        for op, args in rec.value:
            cur.append((op, args))
            if op in ('closePath', 'endPath'):
                contours.append(cur)
                cur = []

        def box(c):
            pts = [p for _, a in c for p in a]
            xs, ys = [p[0] for p in pts], [p[1] for p in pts]
            return min(xs), min(ys), max(xs), max(ys)

        boxes = [box(c) for c in contours]

        def inside(i, j):  # contour i within contour j's box
            a, b = boxes[i], boxes[j]
            return i != j and a[0] >= b[0] and a[1] >= b[1] and a[2] <= b[2] and a[3] <= b[3]

        # each contour with the smallest contour round it: a hole joins its outline
        parent = {}
        for i in range(len(contours)):
            outer = [j for j in range(len(contours)) if inside(i, j)]
            if outer:
                parent[i] = min(outer, key=lambda j: (boxes[j][2] - boxes[j][0]) * (boxes[j][3] - boxes[j][1]))
        # holes of holes are shapes again (a ring's centre dot): only odd depths join
        def depth(i):
            d = 0
            while i in parent:
                i, d = parent[i], d + 1
            return d
        groups = {}
        for i in range(len(contours)):
            root = parent[i] if depth(i) % 2 == 1 else i
            groups.setdefault(root, []).append(i)
        shapes = []
        for root in sorted(groups):
            pen = SVGPathPen(None, ntos=lambda v: ('%.2f' % v).rstrip('0').rstrip('.'))
            tp = TransformPen(pen, (S, 0, 0, -S, 0, ASC * S))
            for i in groups[root]:
                for op, args in contours[i]:
                    getattr(tp, op)(*args)
            shapes.append(pen.getCommands())
        out.append(f"  '{name}': [")
        for d in shapes:
            out.append(f"    '{d}',")
        out.append('  ],')
    out += ['};', '']
    open(os.path.join(ROOT, 'lib/widgets/motion_paths.dart'), 'w').write('\n'.join(out))
    print(len(ICONS), 'icons')


if __name__ == '__main__':
    main()
