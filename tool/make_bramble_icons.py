#!/usr/bin/env python3
"""Builds the app's icon font from Bramble Icons (the Echoes / Bramble Studio set: Phosphor,
Tabler at Phosphor's 1.5 line, Studio's own; MIT licences), keeping only the icons the app
uses (tool/bramble_icons.txt), at plain private-use characters (U+E000 on).

    make_bramble_icons.py <BrambleIcons.ttf> <glyphs_gen.rs>

(both from bramble-office/logic-linux/crates/lg-app: data/icons/ and src/). Writes
assets/icons/BrambleIcons.ttf and lib/bramble_icons.dart (BrambleIcons.export, …,
BrambleIcons.forMaterial). Needs fonttools."""
import os, re, sys
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SETS = {'ph': 'ph', 'fill': 'ph_fill', 'tb': 'tb', 'br': 'br'}
RESERVED = set('''assert break case catch class const continue default do else enum extends false final
finally for if in is new null rethrow return super switch this throw true try var void while with'''.split())


def const_of(name):
    c = re.sub(r'[^A-Za-z0-9]+', '_', name).upper().strip('_')
    return 'N_' + c if c[:1].isdigit() else c


def dart_name(s):
    prefix, name = s.split(':')
    words = re.split(r'[^A-Za-z0-9]+', name)
    camel = words[0] + ''.join(w[:1].upper() + w[1:] for w in words[1:])
    if prefix == 'fill':
        camel += 'Fill'
    elif prefix in ('tb', 'br'):
        camel = prefix + camel[:1].upper() + camel[1:]
    return camel + 'Icon' if camel in RESERVED else camel


def main(font_path, gen_path):
    glyphs, cur = {}, None
    for line in open(gen_path):
        m = re.match(r'pub mod (\w+)', line)
        if m:
            cur = m.group(1)
            glyphs[cur] = {}
            continue
        m = re.search(r'pub const (\w+): &str = "\\u\{([0-9A-F]+)\}"', line)
        if m and cur:
            glyphs[cur][m.group(1)] = int(m.group(2), 16)

    material, extra, rtl = {}, [], set()
    for line in open(os.path.join(ROOT, 'tool/bramble_icons.txt')):
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        parts = line.split()
        if parts[0] == '+':
            extra.append(parts[1])
            continue
        material[parts[0]] = parts[1]
        if 'rtl' in parts[2:]:
            rtl.add(parts[1])

    wanted = sorted({*material.values(), *extra}, key=dart_name)
    old = {}
    for s in wanted:
        p, n = s.split(':')
        old[s] = glyphs[SETS[p]][const_of(n)]
    new = {s: 0xE000 + i for i, s in enumerate(wanted)}

    font = TTFont(font_path)
    opts = subset.Options()
    opts.layout_features = []
    opts.notdef_outline = True
    opts.name_IDs = ['*']
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=set(old.values()))
    sub.subset(font)
    # the same outlines at plain private-use characters
    by_cp = font.getBestCmap()
    for table in font['cmap'].tables:
        table.cmap = {new[s]: by_cp[old[s]] for s in wanted}
    font['name'].setName('Bramble Icons (ChordPro)', 1, 3, 1, 0x409)
    out = os.path.join(ROOT, 'assets/icons/BrambleIcons.ttf')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    font.save(out)

    lines = [
        '// Generated by tool/make_bramble_icons.py from tool/bramble_icons.txt: do not edit.',
        '//',
        '// The app\'s icons: Bramble Icons, the set Echoes (Bramble Studio) uses: Phosphor',
        '// (regular and fill), Tabler outline at Phosphor\'s 1.5 line, MIT licences in',
        '// assets/fonts/LICENSE-phosphor.txt and LICENSE-tabler.txt.',
        '',
        "import 'package:flutter/widgets.dart';",
        '',
        '/// The app\'s icons (one per glyph; `…Fill` = Phosphor\'s filled weight, `tb…` = Tabler).',
        'abstract final class BrambleIcons {',
    ]
    for s in wanted:
        r = ', matchTextDirection: true' if s in rtl else ''
        lines.append(f'  /// {s}')
        lines.append(f"  static const IconData {dart_name(s)} = IconData(0x{new[s]:X}, fontFamily: 'BrambleIcons'{r});")
    lines += [
        '}',
        '',
    ]
    open(os.path.join(ROOT, 'lib/bramble_icons.dart'), 'w').write('\n'.join(lines))
    print(f'{len(wanted)} icons, {os.path.getsize(out)} bytes')


if __name__ == '__main__':
    main(*sys.argv[1:3])
